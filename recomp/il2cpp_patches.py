"""Fill gaps in IL2CPP's runtime that desktop .NET code runs into.

Mono implements these reflection calls; IL2CPP throws NotSupportedException
instead. Libraries such as protobuf-net call them on ordinary paths (asking whether
a setter is init-only), which kills the game. The patches edit the libil2cpp
sources copied into the generated Xcode project, never the Unity install, and
each one checks the exact original text, so an IL2CPP version that differs is
reported instead of being patched blindly.
"""
import os

# Custom modifiers (modreq/modopt) are only metadata annotations such as
# IsExternalInit or IsVolatile. Answering "none" is what callers need to keep
# going: at worst an init-only setter is treated as an ordinary one.
EMPTY_TYPE_ARRAY = "return vm::Array::New(il2cpp_defaults.systemtype_class, 0);"

PATCHES = [
    ("icalls/mscorlib/System.Reflection/RuntimeParameterInfo.cpp",
     'NOT_SUPPORTED_IL2CPP(RuntimeParameterInfo::GetTypeModifiers, "This icall is not supported by il2cpp.");\n        return NULL;'),
    ("icalls/mscorlib/System.Reflection/RuntimeFieldInfo.cpp",
     'NOT_SUPPORTED_IL2CPP(RuntimeFieldInfo::GetTypeModifiers, "This icall is not supported by il2cpp.");\n        return NULL;'),
    ("icalls/mscorlib/System.Reflection/RuntimePropertyInfo.cpp",
     'NOT_SUPPORTED_IL2CPP(MonoPropertyInfo::GetTypeModifiers, "This icall is not supported by il2cpp.");\n\n        return 0;'),
]
INCLUDES = ['#include "vm/Array.h"', '#include "il2cpp-class-internals.h"']
MARKER = "// recomp: patched"

# AppDomain.GetAssemblies: Mono lists assemblies in load order, which in a Unity
# player follows ScriptingAssemblies.json (ordinal file-name order: "X.dll" before
# "XUI.dll"). IL2CPP lists them by generated symbol name ("XUI_" before "X_").
# Games that discover configurators or plugins by walking that list (Timberborn's
# dependency injection) then initialise systems in a different order and break.
ORDER_HEADER = "recomp_assembly_order.h"
GET_ASSEMBLIES_FILE = "icalls/mscorlib/System/AppDomain.cpp"
GET_ASSEMBLIES_ORIGINAL = """        vm::AssemblyVector* assemblies = vm::Assembly::GetAllAssemblies();

        int c = 0;"""
GET_ASSEMBLIES_PATCHED = """        vm::AssemblyVector* assemblies = RecompMonoAssemblyOrder(vm::Assembly::GetAllAssemblies()); """ + MARKER + """

        int c = 0;"""

# Mods (recomp/mods.py): their DLLs are compiled in at port time. The game loads one
# with Assembly.Load(File.ReadAllBytes(path)), which IL2CPP cannot do; the patch looks
# the bytes up by SHA-256 and returns the assembly compiled from them. Until then a mod
# assembly is left out of GetAssemblies, as on Mono, so a disabled or absent mod's
# types (dependency-injection configurators, specs) are not picked up.
MODS_HEADER = "recomp_mod_assemblies.h"
LOAD_RAW_ORIGINAL = """        NOT_SUPPORTED_IL2CPP(AppDomain::LoadAssemblyRaw, "This icall is not supported by il2cpp.");

        return 0;"""
LOAD_RAW_PATCHED = """        const char* name = RecompModAssemblyForBytes((const uint8_t*)vm::Array::GetFirstElementAddress(rawAssembly), vm::Array::GetByteLength(rawAssembly)); """ + MARKER + """
        const Il2CppAssembly* assembly = name ? vm::Assembly::GetLoadedAssembly(name) : NULL;
        if (assembly == NULL)
        {
            vm::Exception::Raise(vm::Exception::GetFileLoadException(
                "[recomp] this DLL was not compiled into the iOS port: IL2CPP cannot load code at run time. "
                "Install the mod on the Mac and port the game again."));
            IL2CPP_UNREACHABLE;
        }
        return (Il2CppObject*)vm::Reflection::GetAssemblyObject(assembly);"""


def order_header(names):
    entries = ",\n".join(f'    "{n}"' for n in names)
    return f"""// Generated by recomp (il2cpp_patches.py): the order Mono loads this game's assemblies in.
#pragma once
#include <algorithm>
#include <climits>
#include <map>
#include <string>
#include <vector>
#include "il2cpp-class-internals.h"
#include "{MODS_HEADER}"

static const char* const kRecompAssemblyOrder[] = {{
{entries}
}};

// Stable-sorts by that order; assemblies not listed keep their place after the listed ones.
static std::vector<const Il2CppAssembly*>* RecompMonoAssemblyOrder(const std::vector<const Il2CppAssembly*>* all)
{{
    static const std::map<std::string, int> rank = [] {{
        std::map<std::string, int> r;
        for (size_t i = 0; i < sizeof(kRecompAssemblyOrder) / sizeof(kRecompAssemblyOrder[0]); ++i)
            r.emplace(kRecompAssemblyOrder[i], (int)i);
        return r;
    }}();
    static thread_local std::vector<const Il2CppAssembly*> ordered;
    ordered.clear();
    for (const Il2CppAssembly* a : *all)
        if (!RecompIsHiddenModAssembly(a->aname.name))
            ordered.push_back(a);
    std::stable_sort(ordered.begin(), ordered.end(), [](const Il2CppAssembly* a, const Il2CppAssembly* b) {{
        auto ra = rank.find(a->aname.name), rb = rank.find(b->aname.name);
        return (ra == rank.end() ? INT_MAX : ra->second) < (rb == rank.end() ? INT_MAX : rb->second);
    }});
    return &ordered;
}}
"""


def mods_header(mod_assemblies):
    names = sorted(mod_assemblies)
    hashes = sorted((h, i) for i, n in enumerate(names) for h in mod_assemblies[n])
    name_entries = ",\n".join(f'    "{n}"' for n in names) or "    nullptr"
    hash_entries = ",\n".join(f'    {{"{h}", {i}}}' for h, i in hashes) or '    {"", 0}'
    return f"""// Generated by recomp (il2cpp_patches.py): mod assemblies compiled into this port.
#pragma once
#include <CommonCrypto/CommonDigest.h>
#include <atomic>
#include <cstdio>
#include <cstring>

static const char* const kRecompModAssemblies[] = {{
{name_entries}
}};
static const int kRecompModAssemblyCount = {len(names)};
static std::atomic<bool> gRecompModLoaded[{max(len(names), 1)}];

// SHA-256 (hex) of each DLL the game may load -> index in kRecompModAssemblies.
static const struct {{ const char* sha256; int index; }} kRecompModHashes[] = {{
{hash_entries}
}};

static int RecompModIndex(const char* name)
{{
    for (int i = 0; i < kRecompModAssemblyCount; ++i)
        if (strcmp(kRecompModAssemblies[i], name) == 0)
            return i;
    return -1;
}}

static bool RecompIsHiddenModAssembly(const char* name)
{{
    int i = RecompModIndex(name);
    return i >= 0 && !gRecompModLoaded[i].load();
}}

// For woven Harmony patches (asmtool harmony): whether the game has loaded this mod assembly.
extern "C" __attribute__((visibility("default"), used)) int recomp_mod_assembly_loaded(const char* name)
{{
    int i = RecompModIndex(name);
    return i >= 0 && gRecompModLoaded[i].load() ? 1 : 0;
}}

// The compiled assembly for these DLL bytes, now visible to GetAssemblies; NULL if none.
static const char* RecompModAssemblyForBytes(const uint8_t* bytes, size_t length)
{{
    unsigned char digest[CC_SHA256_DIGEST_LENGTH];
    CC_SHA256(bytes, (CC_LONG)length, digest);
    char hex[CC_SHA256_DIGEST_LENGTH * 2 + 1];
    for (int i = 0; i < CC_SHA256_DIGEST_LENGTH; ++i)
        snprintf(hex + i * 2, 3, "%02x", digest[i]);
    for (size_t i = 0; i < sizeof(kRecompModHashes) / sizeof(kRecompModHashes[0]); ++i)
        if (strcmp(kRecompModHashes[i].sha256, hex) == 0)
        {{
            int index = kRecompModHashes[i].index;
            gRecompModLoaded[index].store(true);
            printf("[recomp] mods: loaded %s (compiled in)\\n", kRecompModAssemblies[index]);
            return kRecompModAssemblies[index];
        }}
    printf("[recomp] mods: a DLL with SHA-256 %s was not compiled into this port\\n", hex);
    return NULL;
}}
"""


def apply(xcode_dir, assembly_order, log=print, mod_assemblies=None):
    """assembly_order: assembly names (no .dll) in Mono load order.
    mod_assemblies: {assembly name: [SHA-256 of each DLL file that loads as it]}."""
    libil2cpp = os.path.join(xcode_dir, "Il2CppOutputProject", "IL2CPP", "libil2cpp")
    if not os.path.isdir(libil2cpp):
        raise SystemExit(f"libil2cpp sources not found in {xcode_dir}")
    mod_assemblies = mod_assemblies or {}
    with open(os.path.join(libil2cpp, MODS_HEADER), "w") as f:
        f.write(mods_header(mod_assemblies))
    with open(os.path.join(libil2cpp, ORDER_HEADER), "w") as f:
        f.write(order_header(assembly_order))
    path = os.path.join(libil2cpp, GET_ASSEMBLIES_FILE)
    with open(path) as f:
        src = f.read()
    if MARKER not in src:
        if GET_ASSEMBLIES_ORIGINAL not in src:
            raise SystemExit(f"IL2CPP patch does not apply to {GET_ASSEMBLIES_FILE}: update recomp/il2cpp_patches.py")
        src = src.replace(GET_ASSEMBLIES_ORIGINAL, GET_ASSEMBLIES_PATCHED)
        src = src.replace('#include "vm/Assembly.h"', '#include "vm/Assembly.h"\n#include "' + ORDER_HEADER + '"', 1)
        with open(path, "w") as f:
            f.write(src)
        log(f"patched libil2cpp/{GET_ASSEMBLIES_FILE} (Mono assembly order, {len(assembly_order)} assemblies)")
    if "RecompModAssemblyForBytes" not in src:
        if LOAD_RAW_ORIGINAL not in src:
            raise SystemExit(f"IL2CPP patch (Assembly.Load of bytes) does not apply to {GET_ASSEMBLIES_FILE}: "
                             "update recomp/il2cpp_patches.py")
        src = src.replace(LOAD_RAW_ORIGINAL, LOAD_RAW_PATCHED)
        with open(path, "w") as f:
            f.write(src)
        log(f"patched libil2cpp/{GET_ASSEMBLIES_FILE} (Assembly.Load of mod DLLs, {len(mod_assemblies)} compiled in)")
    for rel, original in PATCHES:
        path = os.path.join(libil2cpp, rel)
        with open(path) as f:
            src = f.read()
        if MARKER in src:
            continue
        if original not in src:
            raise SystemExit(f"IL2CPP patch does not apply to {rel}: this Unity version differs; update recomp/il2cpp_patches.py")
        src = src.replace(original, EMPTY_TYPE_ARRAY + " " + MARKER)
        missing = [inc for inc in INCLUDES if inc not in src]
        if missing:
            first = src.index("#include")
            end = src.index("\n", first) + 1
            src = src[:end] + "\n".join(missing) + "\n" + src[end:]
        with open(path, "w") as f:
            f.write(src)
        log(f"patched libil2cpp/{rel}")
