#!/usr/bin/env python3
"""A Mac test clone of a Steam game that runs on the RecompSteam runtime instead of Steam.

    scripts/steam-mac-clone.py <Game.app> [--no-run] [--wait] [-- game arguments]
    scripts/steam-mac-clone.py --build-only

Makes an APFS clone of the game under build/<Game>-steamclone/ (instant, and it takes
no space until something changes), replaces every libsteam_api.dylib in it with the
runtime built for macOS from recomp/native/RecompSteam, re-signs the clone ad hoc with
get-task-allow (so it can be profiled and debugged), and starts it. The game then plays
signed in to Steam without the Steam app: the runtime logs on with the token
`recomp-steam-cli login` keeps in the Keychain, which this script hands to the game in
$RECOMP_STEAM_TOKEN.

Every C function the game's own libsteam_api exports and the runtime does not define is
generated to return 0, as asmtool does for the iOS ports. The game's own files are never
changed: the clone shares their blocks until it writes its own.

Logs: build/<Game>-steamclone/run.log (the runtime, NSLog) and player.log (Unity).
"""
import argparse
import glob
import os
import plistlib
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
RUNTIME = os.path.join(ROOT, "recomp", "native", "RecompSteam")
OUT = os.path.join(ROOT, "build", "recomp-steam")
CLI = os.path.join(OUT, "recomp-steam-cli")
FRAMEWORKS = ["Foundation", "Security", "CoreFoundation"]


def log(msg):
    print(f"[steam-clone] {msg}", flush=True)


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, **kw)


def runtime_sources():
    """The runtime's sources as the ports build them: every top-level C/ObjC file of
    RecompSteam (cli/ is the Terminal tool)."""
    return sorted(p for p in glob.glob(os.path.join(RUNTIME, "*")) if p.endswith((".c", ".m", ".mm")))


def exported_c_functions(dylib):
    """C symbols a library exports (no C++), without the leading underscore."""
    r = subprocess.run(["nm", "-gUj", "-arch", "arm64", dylib], capture_output=True, text=True, check=True)
    return sorted({s[1:] for s in r.stdout.split() if s.startswith("_") and not s.startswith("__Z")})


def build_runtime(original=None, out=OUT):
    """The macOS libsteam_api.dylib from the runtime (arm64 and x86_64); with original,
    plus a "return 0" stub for each of its C exports the runtime lacks."""
    os.makedirs(out, exist_ok=True)
    objs = os.path.join(out, "obj")
    shutil.rmtree(objs, ignore_errors=True)
    os.makedirs(objs)
    archs = ["-arch", "arm64", "-arch", "x86_64"]
    common = ["xcrun", "clang", *archs, "-mmacosx-version-min=11.0", "-O1", "-g", "-fobjc-arc", "-fmodules",
              "-fvisibility=default", "-Wno-unused-function", "-Wno-deprecated-declarations"]
    objects = []
    for src in runtime_sources():
        o = os.path.join(objs, os.path.basename(src) + ".o")
        run(common + ([] if not src.endswith(".mm") else ["-std=c++17"]) + ["-c", src, "-o", o])
        objects.append(o)
    defined = set()
    for o in objects:
        r = subprocess.run(["nm", "-gUj", "-arch", "arm64", o], capture_output=True, text=True, check=True)
        defined |= {s[1:] for s in r.stdout.split() if s.startswith("_")}
    stubs = os.path.join(out, "steam_api_stubs.c")
    missing = [n for n in exported_c_functions(original) if n not in defined] if original else []
    with open(stubs, "w") as f:
        f.write("// Generated by scripts/steam-mac-clone.py: the game's libsteam_api exports the runtime does not define.\n")
        f.write("#include <stdint.h>\n")
        for n in missing:
            f.write(f"__attribute__((used, visibility(\"default\"))) intptr_t {n}(void) {{ return 0; }}\n")
    so = os.path.join(objs, "steam_api_stubs.o")
    run(common + ["-c", stubs, "-o", so])
    dylib = os.path.join(out, "libsteam_api.dylib")
    fw = [x for f in FRAMEWORKS for x in ("-framework", f)]
    run(["xcrun", "clang", *archs, "-mmacosx-version-min=11.0", "-dynamiclib", "-install_name",
         "@loader_path/libsteam_api.dylib", "-lc++", *fw, *objects, so, "-o", dylib])
    log(f"runtime: {dylib} ({len(defined)} symbols from {len(objects)} sources, {len(missing)} generated stubs)")
    return dylib


def build_cli():
    run([os.path.join(RUNTIME, "cli", "build.sh"), OUT], stdout=subprocess.DEVNULL)
    return CLI


def steam_app_id(app):
    from recomp import steam_license
    appid = steam_license.manifest_app_id(app)
    if appid:
        return appid
    txt = os.path.join(os.path.dirname(app), "steam_appid.txt")
    if os.path.isfile(txt):
        return int(open(txt).read().strip() or 0) or None
    return None


def clone(app, appid):
    name = os.path.splitext(os.path.basename(app))[0]
    folder = os.path.join(ROOT, "build", f"{name}-steamclone")
    dest = os.path.join(folder, os.path.basename(app))
    if os.path.exists(dest):
        shutil.rmtree(dest)
    os.makedirs(folder, exist_ok=True)
    # APFS clone (cp -c): instant, shares the game's blocks.
    run(["cp", "-cR", app, dest])
    with open(os.path.join(folder, "steam_appid.txt"), "w") as f:
        f.write(f"{appid}\n")
    return folder, dest


def replace_steam_api(dest, dylib):
    found = [p for p in glob.glob(os.path.join(dest, "**", "libsteam_api.dylib"), recursive=True)]
    for p in found:
        os.remove(p)
        shutil.copy2(dylib, p)
        log(f"replaced {os.path.relpath(p, dest)}")
    if not found:
        sys.exit("the game has no libsteam_api.dylib to replace")


def update_plist(app, dest, appid):
    path = os.path.join(dest, "Contents", "Info.plist")
    with open(path, "rb") as f:
        info = plistlib.load(f)
    info["RecompSteamAppId"] = appid
    # Steam Cloud saves on the clone (session B's recomp/steam_cloud.py), when present.
    try:
        from recomp import steam_cloud, unity_ios
        profile = None
        try:
            profile = unity_ios.game_profile(unity_ios.Game(app))
        except SystemExit:
            pass
        keys = getattr(steam_cloud, "plist_keys", None)
        if keys:
            info.update(keys(app, profile, None, "mac", log))
    except ImportError:
        pass
    with open(path, "wb") as f:
        plistlib.dump(info, f)


def resign(dest, folder):
    ent = os.path.join(folder, "entitlements.plist")
    with open(ent, "wb") as f:
        plistlib.dump({"com.apple.security.get-task-allow": True}, f)
    run(["codesign", "--force", "--deep", "--sign", "-", "--entitlements", ent, dest], stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL)
    log("re-signed ad hoc with get-task-allow")


def launch(dest, folder, appid, args, wait):
    token = subprocess.run([CLI, "token"], capture_output=True, text=True).stdout.strip()
    if not token and not os.environ.get("RECOMP_STEAM_TOKEN"):
        sys.exit(f"no Steam sign-in on this Mac: run `{os.path.relpath(CLI, ROOT)} login` first")
    with open(os.path.join(dest, "Contents", "Info.plist"), "rb") as f:
        exe = os.path.join(dest, "Contents", "MacOS", plistlib.load(f)["CFBundleExecutable"])
    env = dict(os.environ, SteamAppId=str(appid))
    if token:
        env["RECOMP_STEAM_TOKEN"] = token
    out = open(os.path.join(folder, "run.log"), "w")
    cmd = [exe, "-logFile", os.path.join(folder, "player.log"), *args]
    proc = subprocess.Popen(cmd, env=env, cwd=folder, stdout=out, stderr=subprocess.STDOUT, start_new_session=True)
    log(f"started (pid {proc.pid}); logs: {os.path.relpath(folder, ROOT)}/run.log and player.log")
    if wait:
        sys.exit(proc.wait())


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("app", nargs="?", help="the Mac game (.app) from its Steam library")
    ap.add_argument("--build-only", action="store_true", help="only build the runtime and recomp-steam-cli")
    ap.add_argument("--no-run", action="store_true", help="make the clone but do not start it")
    ap.add_argument("--wait", action="store_true", help="wait for the game to quit")
    ap.add_argument("args", nargs="*", help="arguments for the game (after --)")
    a = ap.parse_args()
    build_cli()
    if a.build_only or not a.app:
        build_runtime()
        return
    app = os.path.abspath(a.app.rstrip("/"))
    appid = steam_app_id(app)
    if not appid:
        sys.exit(f"{app}: not in a Steam library (no app id)")
    originals = glob.glob(os.path.join(app, "**", "libsteam_api.dylib"), recursive=True)
    dylib = build_runtime(originals[0] if originals else None)
    folder, dest = clone(app, appid)
    log(f"cloned {os.path.basename(app)} (app {appid}) to {os.path.relpath(dest, ROOT)}")
    replace_steam_api(dest, dylib)
    update_plist(app, dest, appid)
    resign(dest, folder)
    if not a.no_run:
        launch(dest, folder, appid, a.args, a.wait)


if __name__ == "__main__":
    main()
